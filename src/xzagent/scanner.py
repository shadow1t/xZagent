import fnmatch
import os
from dataclasses import dataclass

from .gitignore import GitignoreMatcher
from .languages import MAX_FILE_BYTES, SPECIAL_FILES, TEXT_EXTS, lang_for

DEFAULT_IGNORE_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "__pycache__", ".venv", "venv", "env",
    "dist", "build", "target", ".next", ".nuxt", "vendor", ".idea", ".vscode",
    "coverage", ".mypy_cache", ".pytest_cache", ".tox", ".cache", "out", ".output",
    ".tmp", "tmp", ".npm-cache", ".yarn-cache", ".turbo", ".parcel-cache",
    ".eggs", "storybook-static", "test-results",
    # framework-generated or machine-managed folders: their content is noise
    # for code intelligence. Re-include with a '!name/' negation in .xzagentignore.
    "migrations", "__snapshots__", ".expo", ".angular", ".svelte-kit",
    "Pods", "Carthage", ".gradle", ".terraform", ".serverless",
}

# Lockfiles: generated by package managers, never useful code context.
DEFAULT_NOISE_FILE_NAMES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock",
    "composer.lock", "cargo.lock", "gemfile.lock", "pipfile.lock", "go.sum",
    ".ds_store", "thumbs.db",
}

# Temp/debug/generated file name patterns (matched case-insensitively on the
# basename). Re-include with a '!pattern' negation in .xzagentignore.
DEFAULT_NOISE_FILE_GLOBS = (
    "tmp_*", "temp_*", "*_tmp.*", "*_temp.*", "*.tmp", "*.temp",
    "*_bak.*", "*.bak", "*.orig", "*.rej", "*.patch", "*.swp",
    "*.min.js", "*.min.css", "*.bundle.js", "*.chunk.js",
    "*.log",
)


def _ignored_name(name):
    return name in DEFAULT_IGNORE_DIRS or name.endswith(".egg-info")


def _noise_file(name):
    name = name.lower()
    if name in DEFAULT_NOISE_FILE_NAMES:
        return True
    return any(fnmatch.fnmatch(name, g) for g in DEFAULT_NOISE_FILE_GLOBS)


@dataclass
class ScannedFile:
    path: str
    abspath: str
    ext: str
    size: int
    mtime: float
    lang: str


def scan(root, no_default_skips=False, extra_ignores=None):
    """Walk root and return indexable text files.

    Honors .gitignore (in every visited directory) plus, from the project root,
    a .xzagentignore file (same gitignore syntax), and additional one-off
    ``extra_ignores`` patterns (gitignore syntax, e.g. ['nomad/', '*.g.dart']).

    Unless ``no_default_skips=True``, built-in NOISE is skipped by name:
    temp/debug probe files (tmp_*, *_bak.*), minified bundles (*.min.js),
    lockfiles, log files, and framework artifact folders such as migrations/
    or __snapshots__/ (re-include with a '!pattern' negation in .xzagentignore).
    """
    root = os.path.abspath(root)
    matcher = GitignoreMatcher()
    results = []
    extra_ignores = list(extra_ignores or [])
    for dirpath, dirnames, filenames in os.walk(root):
        gi = os.path.join(dirpath, ".gitignore")
        if os.path.isfile(gi):
            with open(gi, encoding="utf-8", errors="ignore") as fh:
                matcher.add_gitignore(dirpath, fh.read())
        if dirpath == root:
            xzignore = os.path.join(root, ".xzagentignore")
            if os.path.isfile(xzignore):
                with open(xzignore, encoding="utf-8", errors="ignore") as fh:
                    matcher.add_gitignore(root, fh.read())
            if extra_ignores:
                matcher.add_gitignore(root, "\n".join(extra_ignores))
        dirnames[:] = [
            d for d in dirnames
            if not (
                ((no_default_skips is False and _ignored_name(d))
                 or matcher.is_ignored(root, os.path.join(dirpath, d), True))
                and not matcher.is_negation_override(root, os.path.join(dirpath, d), True)
            )
        ]
        for fn in filenames:
            full = os.path.join(dirpath, fn)
            ignores_it = ((no_default_skips is False and (_ignored_name(fn) or _noise_file(fn)))
                          or matcher.is_ignored(root, full, False))
            if ignores_it and not matcher.is_negation_override(root, full, False):
                continue
            if os.path.basename(full) in SPECIAL_FILES:
                ext = SPECIAL_FILES[os.path.basename(full)]
            else:
                ext = os.path.splitext(fn)[1].lower()
                if ext not in TEXT_EXTS:
                    continue
            try:
                st = os.stat(full)
            except OSError:
                continue
            if not os.path.isfile(full) or st.st_size > MAX_FILE_BYTES:
                continue
            results.append(ScannedFile(
                path=os.path.relpath(full, root).replace(os.sep, "/"),
                abspath=full,
                ext=ext,
                size=st.st_size,
                mtime=st.st_mtime,
                lang=lang_for(full) or "text",
            ))
    results.sort(key=lambda f: f.path)
    return results